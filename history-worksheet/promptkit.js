function build(kind, v, level) {
  const slides = kind.id === 'slides';
  const head = slides
    ? (level === 'basic' ? '역사 수업 시간에 교실 화면에 띄울 HTML 슬라이드를 만들어 줘.' : '역사 수업에서 쓸 HTML 슬라이드를 학생 휴대전화와 실시간으로 이어지게 만들어 줘.')
    : (level === 'basic' ? '역사 수업에서 쓸 웹앱을 만들어 줘. 기기 한 대로 혼자 하거나 모둠이 함께 하는 방식이야.' : '역사 수업에서 쓸 웹앱을 만들어 줘. 학생 여럿이 각자 기기로 동시에 들어오는 실시간 방식이야.');
  const body = (level === 'basic' ? kind.basic : kind.adv)(v);
  if (v.extra) body.push(`그리고 이것도 넣어 줘: ${v.extra}`);
  return [head, '', ...body, '', ...common(v, level, slides)].join('\n');
}

